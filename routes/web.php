<?php

use App\Http\Controllers\Admin;
use App\Http\Controllers\BookingController;
use App\Http\Controllers\PaymentController;
use App\Http\Controllers\SearchController;
use App\Http\Controllers\SeatController;
use App\Http\Controllers\TicketController;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Web Routes
|--------------------------------------------------------------------------
| Routes define the URL → Controller mapping (the "R" in MVC).
| All routes use CSRF protection automatically (VerifyCsrfToken middleware).
|--------------------------------------------------------------------------
*/

// ─── Public Routes ────────────────────────────────────────────────────────

// Home page: search form
Route::get('/', [SearchController::class, 'index'])->name('home');

// Search results: GET /search?source=...&destination=...&date=...
Route::get('/search', [SearchController::class, 'search'])->name('search');

// Seat map: show all seats for a given schedule (route model binding)
Route::get('/seats/{schedule}', [SeatController::class, 'show'])->name('seats.show');

// ─── Authenticated User Routes ────────────────────────────────────────────
// 'auth' middleware (from Breeze) ensures user is logged in

Route::middleware('auth')->group(function () {

    // POST /book — hold a seat and create a pending booking
    Route::post('/book', [BookingController::class, 'store'])->name('booking.store');

    // My bookings list
    Route::get('/my-bookings', [BookingController::class, 'myBookings'])->name('bookings.index');

    // Cancel a booking from the My Bookings page
    Route::post('/bookings/{booking}/cancel', [BookingController::class, 'cancel'])
         ->name('bookings.cancel');

    // Payment page — shows fare, countdown timer
    Route::get('/payment/{booking}', [PaymentController::class, 'show'])->name('payment.show');

    // Confirm payment (simulated)
    Route::post('/payment/{booking}/pay', [PaymentController::class, 'pay'])->name('payment.pay');

    // Cancel from payment page
    Route::post('/payment/{booking}/cancel', [PaymentController::class, 'cancel'])
         ->name('payment.cancel');

    // E-ticket display with QR code
    Route::get('/ticket/{booking}', [TicketController::class, 'show'])->name('ticket.show');
});

// ─── Admin Routes ─────────────────────────────────────────────────────────
// Both 'auth' AND 'admin' middleware required.
// 'admin' middleware checks role === 'admin' (see App\Http\Middleware\AdminMiddleware)

Route::middleware(['auth', 'admin'])->prefix('admin')->name('admin.')->group(function () {

    // Dashboard: counts and revenue summary
    Route::get('/', [Admin\DashboardController::class, 'index'])->name('dashboard');

    // Resource routes: automatically create index, create, store, edit, update, destroy
    Route::resource('buses',     Admin\BusController::class);
    Route::resource('routes',    Admin\RouteController::class);
    Route::resource('schedules', Admin\ScheduleController::class);

    // Bookings list (read-only for admin, with status filter)
    Route::get('bookings', [Admin\BookingController::class, 'index'])->name('bookings.index');
});

// ─── Auth Routes (Login, Register, Logout) ────────────────────────────────
// Generated by Laravel Breeze: includes /login, /register, /logout, etc.
require __DIR__.'/auth.php';
